// Regenerate the checked-in lookup table using the same URL normalization as BrowseCore.
import Foundation

let sourceURL = CommandLine.arguments.dropFirst().first.map { URL(fileURLWithPath: $0) }
    ?? URL(string: "https://publicsuffix.org/list/public_suffix_list.dat")!
let source = try String(contentsOf: sourceURL, encoding: .utf8)
let sections = source.components(separatedBy: "// ===BEGIN ICANN DOMAINS===")
guard sections.count == 2, sections[1].contains("// ===END PRIVATE DOMAINS===") else {
    throw CocoaError(.fileReadCorruptFile)
}

var rules = Set<String>()
for line in sections[1].split(whereSeparator: \.isNewline) {
    guard let rule = line.split(whereSeparator: \.isWhitespace).first, !rule.hasPrefix("//") else { continue }
    let prefix = rule.hasPrefix("!") ? "!" : rule.hasPrefix("*.") ? "*." : ""
    let name = rule.dropFirst(prefix.count)
    guard let host = URL(string: "https://\(name)/")?.host?.lowercased(),
          !host.isEmpty, host.utf8.allSatisfy({ (97...122).contains($0) || (48...57).contains($0) || $0 == 45 || $0 == 46 }) else {
        throw NSError(domain: "PublicSuffixList", code: 1,
                      userInfo: [NSLocalizedDescriptionKey: "Invalid domain rule: \(rule)"])
    }
    rules.insert(prefix + host)
}

// Equal-width rows let lookup jump directly to the midpoint of a bucket.
let buckets = Dictionary(grouping: rules.sorted(), by: { $0.utf8.count })
var output = "// Generated by scripts/update-public-suffix-list.swift; do not edit.\n"
output += sections[0].trimmingCharacters(in: .whitespacesAndNewlines) + "\n\n"
output += "enum PublicSuffixSnapshot {\n    static func rows(ofLength length: Int) -> StaticString? {\n        switch length {\n"
for (length, bucket) in buckets.sorted(by: { $0.key < $1.key }) {
    let rows = bucket.joined(separator: "\n")
    output += "        case \(length): return \"\"\"\n\(rows)\n\"\"\"\n"
}
output += "        default: return nil\n        }\n    }\n}\n"

let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
try output.write(to: root.appendingPathComponent("Sources/BrowseCore/PublicSuffixSnapshot.swift"),
                 atomically: true, encoding: .utf8)
