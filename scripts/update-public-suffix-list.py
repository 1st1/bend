#!/usr/bin/env python3
"""Regenerate the offline PSL snapshot from the official list or a local copy."""
from pathlib import Path
import sys
import urllib.request

source = (Path(sys.argv[1]).read_text() if len(sys.argv) > 1 else
          urllib.request.urlopen('https://publicsuffix.org/list/public_suffix_list.dat').read().decode('utf-8'))
assert '// ===BEGIN ICANN DOMAINS===' in source
assert '// ===END PRIVATE DOMAINS===' in source
assert '"""' not in source
output = Path(__file__).resolve().parent.parent / 'Sources/BrowseCore/PublicSuffixSnapshot.swift'
output.write_text('// Generated by scripts/update-public-suffix-list.py; do not edit.\n'
                  '// Source and MPL-2.0 license notice are preserved below.\n'
                  'enum PublicSuffixSnapshot {\n    static let text = #"""\n' + source + '\n"""#\n}\n')
